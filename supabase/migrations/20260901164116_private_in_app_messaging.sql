      (p_sender_kind = 'gm' and m.sender_kind = 'gm')
      or (p_sender_kind = 'citizen' and m.sender_kind = 'citizen' and m.sender_seat = p_sender_seat)
    );

  get diagnostics changed = row_count;
  return changed;
end;
$function$;

