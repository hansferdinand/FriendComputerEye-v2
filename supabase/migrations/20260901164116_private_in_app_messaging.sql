create or replace function public.fc_message_player_send(
  p_token text,
  p_recipient_kind text,
  p_recipient_seat integer,
  p_body text
)
returns bigint
language plpgsql
security definer
set search_path = public, extensions
as $function$
declare
  token_room text;
  token_seat smallint;
  room_hash bytea;
  p2p_enabled boolean;
  message_id bigint;
begin
  select i.room, i.seat, i.gm_key_hash into token_room, token_seat, room_hash
  from public.fc_message_token_identity(p_token) i;
  if token_room is null then return null; end if;
  if p_body is null or char_length(btrim(p_body)) < 1 or char_length(p_body) > 2000 then return null; end if;

  if p_recipient_kind = 'gm' then
    p_recipient_seat := null;
  elsif p_recipient_kind = 'citizen' then
    select coalesce(s.allow_player_to_player, false) into p2p_enabled
    from public.fc_message_settings s where s.room = token_room;
    if not coalesce(p2p_enabled, false) or p_recipient_seat is null or p_recipient_seat = token_seat then
      return null;
    end if;
    if not exists (
      select 1 from public.fc_citizens c where c.room = token_room and c.seat = p_recipient_seat
    ) then return null; end if;
  else
    return null;
  end if;

  perform public.fc_message_prune(token_room);
  if (
    select count(*) >= 20
    from public.fc_direct_messages m
    where m.room = token_room
      and m.sender_kind = 'citizen'
      and m.sender_seat = token_seat
      and m.created_at >= now() - interval '1 minute'
  ) then return null; end if;

  insert into public.fc_direct_messages(
    room, sender_kind, sender_seat, recipient_kind, recipient_seat, body_cipher
  )
  values (
    token_room,
    'citizen',
    token_seat,
    p_recipient_kind,
    p_recipient_seat::smallint,
    extensions.pgp_sym_encrypt(btrim(p_body), encode(room_hash, 'hex'))
  )
  returning public.fc_direct_messages.id into message_id;

  return message_id;
end;
$function$;

create or replace function public.fc_message_player_mark_read(
  p_token text,
  p_sender_kind text,
  p_sender_seat integer default null
)
returns integer
language plpgsql
security definer
set search_path = public, extensions
as $function$
