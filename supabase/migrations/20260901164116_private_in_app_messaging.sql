create or replace function public.fc_message_player_identity(p_token text)
returns table(
  room text,
  seat smallint,
  citizen_id text,
  display_name text,
  allow_player_to_player boolean,
  retention_hours smallint,
  gm_can_read_player_to_player boolean,
  expires_at timestamptz
)
language plpgsql
security definer
set search_path = public, extensions
as $function$
declare
  token_room text;
  token_seat smallint;
begin
  select i.room, i.seat into token_room, token_seat
  from public.fc_message_token_identity(p_token) i;
  if token_room is null then return; end if;

  update public.fc_message_participants p
  set last_seen_at = now()
  where p.room = token_room
    and p.seat = token_seat
    and (p.last_seen_at is null or p.last_seen_at < now() - interval '1 minute');

  return query
  select c.room,
         c.seat,
         c.citizen_id,
         c.display_name,
         coalesce(s.allow_player_to_player, false),
         coalesce(s.retention_hours, 168::smallint),
         false,
         p.expires_at
  from public.fc_citizens c
  join public.fc_message_participants p on p.room = c.room and p.seat = c.seat
  left join public.fc_message_settings s on s.room = c.room
  where c.room = token_room and c.seat = token_seat;
end;
$function$;

create or replace function public.fc_message_player_directory(p_token text)
returns table(seat smallint, citizen_id text, display_name text)
language plpgsql
security definer
set search_path = public, extensions
as $function$
declare
  token_room text;
  token_seat smallint;
  p2p_enabled boolean;
begin
  select i.room, i.seat into token_room, token_seat
  from public.fc_message_token_identity(p_token) i;
  if token_room is null then return; end if;

  select coalesce(s.allow_player_to_player, false) into p2p_enabled
  from public.fc_message_settings s where s.room = token_room;
  if not coalesce(p2p_enabled, false) then return; end if;

  return query
  select c.seat, c.citizen_id, c.display_name
  from public.fc_citizens c
  where c.room = token_room and c.seat <> token_seat
  order by c.seat;
end;
$function$;

